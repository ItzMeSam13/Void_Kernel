# ── Processing status (reused across all image sub-components) ───────────────

class ProcessingStatus(str, Enum):
    """Outcome of a sub-component's analysis run."""
    SUCCESS = "success"
    ERROR = "error"
    NOT_ASSESSED = "not_assessed"


# ── CLIP Claim-Image Similarity ─────────────────────────────────────────────

class ClipSimilarityInput(BaseModel):
    """Input contract for the CLIP claim-image similarity component.

    Accepts a validated local file path to an image and a non-empty textual
    claim or description.  Neither field depends on FastAPI ``UploadFile``,
    LangGraph state, or any other module's internal objects.
    """
    image_path: str = Field(
        ...,
        description="Absolute or relative local file path to the image.",
    )
    claim_text: str = Field(
        ...,
        min_length=1,
        description="Non-empty textual claim or description to compare with the image.",
    )


class ClipSimilarityOutput(BaseModel):
    """Output contract for the CLIP claim-image similarity component.

    Contains:
    - A cosine-similarity score (range [-1, 1]) between the image and text
      embeddings produced by the CLIP model.  This is NOT a probability that a
      claim is true or false; it measures how semantically close the image and
      text representations are in the shared CLIP embedding space.
    - An optional ``logits_per_image`` score — the raw (unnormalised) logit
      output from the model, kept separate from the cosine similarity so
      consumers can choose which metric to use.
    - Model identification and processing metadata.
    - Structured error information when analysis cannot be completed.
    """
    status: ProcessingStatus = Field(
        ...,
        description="Processing outcome: success, error, or not_assessed.",
    )
    similarity_score: Optional[float] = Field(
        None,
        description=(
            "Cosine similarity between the normalised CLIP image embedding and "
            "text embedding.  Range: [-1.0, 1.0].  Higher → more semantically "
            "similar.  None when status != 'success'."
        ),
    )
    logits_per_image: Optional[float] = Field(
        None,
        description=(
            "Raw (unnormalised) logit score from CLIPModel.  Kept distinct from "
            "cosine similarity to avoid conflation.  None when status != 'success'."
        ),
    )
    comparison_method: str = Field(
        default="cosine_similarity",
        description="Metric used for the primary similarity_score.",
    )
    model_id: str = Field(
        default="openai/clip-vit-base-patch32",
        description="Hugging Face model identifier used for inference.",
    )
    model_revision: Optional[str] = Field(
        None,
        description="Git revision / commit hash of the loaded model, when available.",
    )
    error_message: Optional[str] = Field(
        None,
        description="Human-readable error description when status is 'error'.",
    )
    limitations: Optional[str] = Field(
        None,
        description=(
            "Structured limitation note when analysis completed but with "
            "caveats (e.g. extremely short text, very small image)."
        ),
    )


