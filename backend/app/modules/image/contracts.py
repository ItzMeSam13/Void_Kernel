# ── Smaug AI-Generated Image Detection ─────────────────────────────────────

class SmaugDetectionInput(BaseModel):
    """Input contract for the Smaug AI-generated image detection component.

    Accepts a validated local file path to an image.  Uses the same
    ``image_path`` representation as the other image sub-components for
    consistency across the module.

    The detection is independent of any claim text — Smaug estimates the
    probability that the image itself was AI-generated, irrespective of any
    caption or claim context.
    """
    image_path: str = Field(
        ...,
        description="Absolute or relative local file path to the image.",
    )
    detection_threshold: float = Field(
        default=0.5,
        ge=0.0,
        le=1.0,
        description=(
            "Probability threshold above which the optional ``label`` field is "
            "set to 'likely_ai_generated'.  Default 0.5 (per Smaug model card). "
            "This threshold is NOT universally optimal — treat the raw "
            "``ai_probability`` as the primary signal."
        ),
    )


class SmaugDetectionOutput(BaseModel):
    """Output contract for the Smaug AI-generated image detection component.

    Contains:
    - ``ai_probability``: the raw probability [0, 1] returned by the Smaug
      detector that the image was AI-generated.  This is the primary output
      and the only value that should be passed to downstream fusion.
    - ``label``: an optional human-readable interpretation based on
      ``detection_threshold``.  It is clearly qualified and must NOT be used
      as a definitive verdict.
    - Model identification and processing metadata.
    - Structured error information when detection cannot be completed.

    Important limitations (per architecture.md §1 Guiding Principle 2):
    - A low score does NOT prove an image is genuine or unmanipulated.
    - A high score does NOT prove the depicted event did not occur.
    - Smaug does not localise manipulated regions — that is a separate
      component (ManTraNet/BusterNet).
    - This score is evidence, not proof.  Interpretation belongs to Module 7.
    """
    status: ProcessingStatus = Field(
        ...,
        description="Processing outcome: success, error, or not_assessed.",
    )
    ai_probability: Optional[float] = Field(
        None,
        description=(
            "Raw probability [0.0, 1.0] that the image is AI-generated, as "
            "returned by the Smaug detector.  None when status != 'success'. "
            "This is the primary signal — do NOT apply a second sigmoid."
        ),
    )
    label: Optional[str] = Field(
        None,
        description=(
            "Optional qualified interpretation: 'likely_ai_generated' when "
            "ai_probability >= detection_threshold, 'not_flagged_as_ai_generated' "
            "otherwise.  This is NOT a definitive verdict."
        ),
    )
    detection_threshold: Optional[float] = Field(
        None,
        description="Threshold used to derive the optional label field.",
    )
    model_id: str = Field(
        default="abacusai/Smaug-AI-Image-Detector",
        description="Hugging Face model identifier used for inference.",
    )
    model_revision: Optional[str] = Field(
        None,
        description="Git revision / commit hash of the loaded model, when available.",
    )
    error_message: Optional[str] = Field(
        None,
        description="Human-readable error description when status is 'error'.",
    )


# ── PaddleOCR Text Extraction ────────────────────────────────────────────────

class OcrStatus(str, Enum):
    """Fine-grained outcome for OCR, distinguishing 'ran but found nothing'
    from 'ran and found text' and 'failed to run'."""
    TEXT_DETECTED = "text_detected"
    NO_TEXT_DETECTED = "no_text_detected"
    ERROR = "error"


class OcrTextRegion(BaseModel):
    """One detected text region returned by PaddleOCR.

    Coordinates use the PaddleOCR convention: a list of four (x, y) corner
    points as [[x0,y0],[x1,y1],[x2,y2],[x3,y3]] (polygon / quad).
    ``confidence`` is the recognition confidence in [0, 1] as reported by the
    model, not a statement about factual accuracy.
    """
    text: str = Field(
        ...,
        description="Recognized text string for this region.",
    )
    confidence: Optional[float] = Field(
        None,
        ge=0.0,
        le=1.0,
        description="Recognition confidence [0, 1] as reported by PaddleOCR.",
    )
    bounding_box: Optional[List[List[float]]] = Field(
        None,
        description=(
            "Polygon coordinates as [[x0,y0],[x1,y1],[x2,y2],[x3,y3]]. "
            "None when the model does not return coordinates."
        ),
    )


class OcrInput(BaseModel):
    """Input contract for the PaddleOCR text extraction component.

    Uses the same ``image_path`` representation as the other image
    sub-components for consistency.
    """
    image_path: str = Field(
        ...,
        description="Absolute or relative local file path to the image.",
    )


class OcrOutput(BaseModel):
    """Output contract for the PaddleOCR text extraction component.

    Design notes:
    - ``status`` distinguishes 'text_detected', 'no_text_detected', and 'error'.
      An empty-result image is NOT an error — it is ``no_text_detected``.
    - ``regions`` contains one entry per detected text region, in reading order
      where PaddleOCR preserves it.
    - ``combined_text`` is the concatenation of all region texts joined by
      newlines, provided as a convenience for downstream fact-checking.
      It is raw extracted text — NOT a truth claim, NOT a substitute for the
      user's supplied claim, and NOT fact-checked by this component.
    - Recognition confidence reflects the model's character-recognition
      certainty, not the factual accuracy of the text.
    """
    status: OcrStatus = Field(
        ...,
        description=(
            "Outcome: 'text_detected', 'no_text_detected', or 'error'. "
            "'no_text_detected' is a valid successful outcome for images "
            "without embedded text."
        ),
    )
    regions: List[OcrTextRegion] = Field(
        default_factory=list,
        description=(
            "Detected text regions in reading order.  Empty when status is "
            "'no_text_detected' or 'error'."
        ),
    )
    combined_text: str = Field(
        default="",
        description=(
            "All recognized text joined by newlines, for downstream use as "
            "evidence.  Empty when no text was detected or on error.  "
            "This is raw extracted text — NOT a verified claim."
        ),
    )
    engine: str = Field(
        default="paddleocr",
        description="OCR engine identifier.",
    )
    error_message: Optional[str] = Field(
        None,
        description="Human-readable error description when status is 'error'.",
    )


